"""Pack the engine, the benchmark and a snapshot into ONE self-contained script for `colab run`.

`colab run` sends only the script file, so the code and inputs ride inside it (base64 tar.gz). On the VM
the script times `pip install arch`, unpacks, and runs bench.py with the given arguments; results come
back on stdout between BENCH-JSON markers, so nothing has to be downloaded.

Usage: python benchmarks/make_job.py OUT.py --snapshot benchmarks/reference/inputs.json [bench.py args...]
"""
import base64
import io
import os
import sys
import tarfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILES = ["DynamicPortfolioOptimizationFunc.py", "mso", "benchmarks/bench.py", "benchmarks/load_snapshot.py"]

TEMPLATE = r'''# Generated by benchmarks/make_job.py - do not edit.
import base64, io, os, subprocess, sys, tarfile, tempfile, time
T0 = time.time()
print(f"[job] started on the VM at {time.strftime('%Y-%m-%d %H:%M:%S')}", flush=True)
if os.environ.get("BENCH_SKIP_INSTALL") != "1":   # set only for a local dry run, where arch is installed
    t = time.time()
    r = subprocess.run([sys.executable, "-m", "pip", "install", "-q", "arch"], capture_output=True, text=True)
    print(f"[job] pip install arch: {time.time() - t:.1f} s, exit {r.returncode}", flush=True)
    if r.returncode:
        print(r.stdout[-2000:], r.stderr[-2000:], flush=True)
        sys.exit(2)
work = "/content/job" if os.path.isdir("/content") else tempfile.mkdtemp(prefix="bench-job-")
os.makedirs(work, exist_ok=True)
tarfile.open(fileobj=io.BytesIO(base64.b64decode(PAYLOAD)), mode="r:gz").extractall(work, filter="data")
os.chdir(work)
os.environ["MPLBACKEND"] = "Agg"
sys.argv = ["benchmarks/bench.py"] + ARGS
import runpy
try:
    runpy.run_path("benchmarks/bench.py", run_name="__main__")
finally:
    print(f"[job] finished, {time.time() - T0:.1f} s on the VM", flush=True)
'''


def main():
    out, args = sys.argv[1], sys.argv[2:]
    snap = args[args.index("--snapshot") + 1]
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        for f in FILES + [snap]:
            tar.add(os.path.join(ROOT, f), arcname=f,
                    filter=lambda ti: None if "__pycache__" in ti.name else ti)
    payload = base64.b64encode(buf.getvalue()).decode()
    with open(out, "w") as f:
        f.write(f"PAYLOAD = {payload!r}\nARGS = {args!r}\n" + TEMPLATE)
    print(f"wrote {out}: payload {len(payload) / 1024:.0f} KiB, args {args}")


if __name__ == "__main__":
    main()
