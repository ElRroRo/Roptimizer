"""Packing a run into ONE self-contained script for `colab run` (generalises benchmarks/make_job.py, #5).

`colab run` sends only the script file, so the mso package and the run's frozen files ride inside it as a
base64 tar.gz. On the VM the script installs `arch`, unpacks, runs `python -m mso run ...` and prints the
result JSON (gzip + base64) between MSO-RESULT markers, so nothing has to be uploaded or downloaded.
Inputs are frozen on the laptop before packing (fits included), so laptop and A100 runs share identical
inputs (#9) and the VM never calls Yahoo.
"""
import base64
import gzip
import io
import json
import os
import tarfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BEGIN, END = "MSO-RESULT-BEGIN", "MSO-RESULT-END"

TEMPLATE = r'''# Generated by mso/job.py - do not edit.
import base64, gzip, io, os, subprocess, sys, tarfile, tempfile, time
T0 = time.time()
print(f"[job] started on the VM at {time.strftime('%Y-%m-%d %H:%M:%S')}", flush=True)
try:
    smi = subprocess.run(["nvidia-smi", "--query-gpu=name,memory.total", "--format=csv,noheader"],
                         capture_output=True, text=True, timeout=30).stdout.strip()
    print(f"[job] GPU: {smi}", flush=True)
except Exception as e:
    print(f"[job] nvidia-smi failed: {e}", flush=True)
if os.environ.get("MSO_SKIP_INSTALL") != "1":   # set only for a local dry run, where arch is installed
    t = time.time()
    r = subprocess.run([sys.executable, "-m", "pip", "install", "-q", "arch"], capture_output=True, text=True)
    print(f"[job] pip install arch: {time.time() - t:.1f} s, exit {r.returncode}", flush=True)
    if r.returncode:
        print(r.stdout[-2000:], r.stderr[-2000:], flush=True)
        sys.exit(2)
work = "/content/mso-job" if os.path.isdir("/content") else tempfile.mkdtemp(prefix="mso-job-")
os.makedirs(work, exist_ok=True)
tarfile.open(fileobj=io.BytesIO(base64.b64decode(PAYLOAD)), mode="r:gz").extractall(work, filter="data")
os.chdir(work)
sys.path.insert(0, work)
os.environ["MPLBACKEND"] = "Agg"
code = 0
for i, args in enumerate(RUNS):
    # Each run in its own process, so it starts on a clean GPU (2026-10-29: in one process, the fourth run
    # of a job found about 22 GB still in use and sized its bank at 13.6M paths instead of 30M).
    print(f"[job] run {i + 1}/{len(RUNS)}: {' '.join(args)}", flush=True)
    p = subprocess.Popen([sys.executable, "-u", "-m", "mso"] + args, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                         text=True, bufsize=1)
    for line in p.stdout:
        print(line, end="", flush=True)
    p.wait()
    code = code or p.returncode
    out = args[args.index("--out") + 1]
    if os.path.exists(out):
        blob = base64.b64encode(gzip.compress(open(out, "rb").read())).decode()
        print(f"MSO-RESULT-BEGIN {i}", flush=True)
        for j in range(0, len(blob), 76):
            print(blob[j:j + 76])
        print("MSO-RESULT-END", flush=True)
print(f"[job] finished, {time.time() - T0:.1f} s on the VM, exit {code}", flush=True)
sys.exit(code)
'''


def build(out_script, files, args):
    """files: {name inside the job: local path}; args: `python -m mso` arguments (one run) or a list of
    them (several runs on one VM, sharing its start-up); every run's arguments must include --out."""
    runs = [list(args)] if args and isinstance(args[0], str) else [list(a) for a in args]
    if any("--out" not in r for r in runs):
        raise ValueError("every run's args need --out")
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        tar.add(os.path.join(ROOT, "mso"), arcname="mso",
                filter=lambda ti: None if "__pycache__" in ti.name else ti)
        for arc, path in files.items():
            tar.add(path, arcname=arc)
    payload = base64.b64encode(buf.getvalue()).decode()
    with open(out_script, "w") as f:
        f.write(f"PAYLOAD = {payload!r}\nRUNS = {runs!r}\n" + TEMPLATE)
    return len(payload)


def extract_all(stdout):
    """{run index: result JSON} for every result printed between the markers."""
    out = {}
    for part in stdout.split(BEGIN)[1:]:
        head, _, rest = part.partition("\n")
        if END not in rest:
            continue
        body = rest.split(END, 1)[0]
        blob = "".join(l.strip() for l in body.splitlines() if l.strip() and not l.startswith("@@MSO"))
        out[int(head.strip() or 0)] = json.loads(gzip.decompress(base64.b64decode(blob)))
    return out


def extract(stdout):
    """The (first) run's result JSON, or None when the job ended without one."""
    return extract_all(stdout).get(0)
